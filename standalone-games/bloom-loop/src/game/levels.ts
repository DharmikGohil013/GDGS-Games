export function chapterForLevel(levelId: number): Chapter {
  return CHAPTERS.find(c => levelId >= c.firstLevel && levelId <= c.lastLevel) ?? CHAPTERS[0];
}

// Layouts are drawn row by row, one letter per flower and '.' for an empty cell.
const COLOR_CODES: Record<string, FlowerColor> = {
  L: 'lilac',
  S: 'sky',
  O: 'orange',
  G: 'gold',
  M: 'mint',
  C: 'coral',
};

// Bees are listed in queue order as colour letter + pollen shots, e.g. 'L4 S4'.
function garden(
  id: number,
  name: string,
  description: string,
  rows: string[],
  bees: string,
  options: Pick<LevelData, 'loopCapacity'> = {}
): LevelData {
  return {
    id,
    name,
    description,
    gridRows: rows.length,
    gridCols: rows[0].length,
    layout: rows.map(row => [...row].map(cell => (cell === '.' ? null : COLOR_CODES[cell]))),
    beeQueue: bees.split(' ').map(bee => ({ color: COLOR_CODES[bee[0]], ammo: Number(bee.slice(1)) })),
    ...options,
  };
}

